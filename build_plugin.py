"""Produce the one-file plugin accepted by Cardinal's Telegram uploader."""
from pathlib import Path
import zipfile


def build_manual_login(root=None):
    root = Path(root or Path(__file__).parent)
    target = root / 'dist' / 'claude-windows-login-0.3.1.zip'
    target.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED) as z:
        for name in ('tools/claude_manual_login.py', 'tools/open_claude_manual.cmd', 'CLAUDE_MANUAL_LOGIN_RU.md'):
            z.write(root / name, name)
    return target


def build(root=None):
    root = Path(root or Path(__file__).parent)
    sources = {name: (root / (name + '.py')).read_text(encoding='utf-8')
               for name in ('remail', 'rental', 'claude_browser_actions', 'lot_rules')}
    content = '# Claude Rental 0.3.0 — generated by build_plugin.py; sources are in the repository.\n'
    content += '_EMBEDDED_SOURCES = ' + repr(sources) + '\n\n'
    content += (root / 'claude_rental_plugin.py').read_text(encoding='utf-8')
    compile(content, 'claude_rental_plugin.py', 'exec')
    target = root / 'dist'
    target.mkdir(exist_ok=True)
    (target / 'claude_rental_plugin.py').write_text(content, encoding='utf-8')
    with zipfile.ZipFile(target / 'claude-rental-plugin-0.3.0.zip', 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('plugins/claude_rental_plugin.py', content)
        for name in ('INSTALL_PLUGIN_RU.md', 'CLAUDE_AUTOMATION_PLAN.md', 'CLAUDE_WINDOWS_RU.md',
                     'config.example.json', 'tools/claude_session.py', 'tools/setup_claude_browser.cmd',
                     'tools/open_claude_session.cmd'):
            z.write(root / name, name)
    return target / 'claude_rental_plugin.py'


if __name__ == '__main__':
    print(build())
