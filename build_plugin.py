"""Build complete release archives and the single-file Cardinal plugin."""
from pathlib import Path
import zipfile

VERSION = '0.4.2'
TOOL_FILES = (
    'tools/claude_manual_login.py', 'tools/open_claude_manual.cmd',
    'tools/claude_account_check.py', 'tools/check_claude_account.cmd',
    'tools/setup_claude_check.cmd', 'tools/claude_account_menu.py', 'tools/claude_account.cmd',
    'CLAUDE_BROWSER_CHECK_RU.md', 'CLAUDE_MANUAL_LOGIN_RU.md', 'UPDATE_0.4.2_RU.txt',
)


def write_tools(archive, root):
    for name in TOOL_FILES:
        archive.write(root / name, name)
    for name in ('claude_browser_ui.py', 'claude_browser_actions.py'):
        archive.write(root / name, 'tools/' + name)


def tool_bundle(prefix, root=None):
    root = Path(root or Path(__file__).parent)
    target = root / 'dist' / f'{prefix}-{VERSION}.zip'
    target.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED) as archive:
        write_tools(archive, root)
    return target


def build_manual_login(root=None):
    return tool_bundle('claude-windows-login', root)


def build_browser_check(root=None):
    return tool_bundle('claude-browser-check', root)


def build(root=None):
    root = Path(root or Path(__file__).parent)
    sources = {name: (root / (name + '.py')).read_text(encoding='utf-8')
               for name in ('remail', 'rental', 'claude_browser_actions', 'claude_browser_ui', 'claude_auto_kick', 'lot_rules')}
    for name in ('claude_manual_login', 'claude_account_check'):
        sources[name] = (root / 'tools' / (name + '.py')).read_text(encoding='utf-8')
    content = f'# Claude Rental {VERSION} — generated by build_plugin.py; sources are in the repository.\n'
    content += '_EMBEDDED_SOURCES = ' + repr(sources) + '\n\n'
    content += (root / 'claude_rental_plugin.py').read_text(encoding='utf-8')
    compile(content, 'claude_rental_plugin.py', 'exec')
    target = root / 'dist'
    target.mkdir(exist_ok=True)
    (target / 'claude_rental_plugin.py').write_text(content, encoding='utf-8')
    with zipfile.ZipFile(target / f'claude-rental-plugin-{VERSION}.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
        archive.writestr('plugins/claude_rental_plugin.py', content)
        write_tools(archive, root)
        for name in ('INSTALL_PLUGIN_RU.md', 'CLAUDE_AUTOMATION_PLAN.md', 'CLAUDE_WINDOWS_RU.md',
                     'AUTO_KICK_RU.md', 'AUTO_KICK_TESTS_RU.md', 'config.example.json',
                     'tools/claude_session.py', 'tools/setup_claude_browser.cmd', 'tools/open_claude_session.cmd'):
            archive.write(root / name, name)
    return target / 'claude_rental_plugin.py'


if __name__ == '__main__':
    print(build())
